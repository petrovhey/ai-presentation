from fpdf import FPDF

class SlidePDF(FPDF):
    def __init__(self):
        super().__init__(orientation='L', unit='mm', format='A4')
        self.set_auto_page_break(False)
        self.margin = 15
        self.content_w = 297 - 2*self.margin
        self.content_h = 210 - 2*self.margin
        self.add_font("DejaVu", "", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", uni=True)
        self.add_font("DejaVu", "B", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", uni=True)
        self.add_font("DejaVu", "I", "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Oblique.ttf", uni=True)
        self.add_font("DejaVu", "BI", "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-BoldOblique.ttf", uni=True)
        self.page_bg = (245, 247, 250)
        self.accent = (31, 78, 120)
        self.text = (33, 37, 41)
        self.light = (120, 144, 156)

    def new_slide(self, title):
        self.add_page()
        # Фон
        self.set_fill_color(*self.page_bg)
        self.rect(0, 0, 297, 210, style='F')
        # Верхняя полоса
        self.set_fill_color(*self.accent)
        self.rect(0, 0, 297, 12, style='F')
        # Заголовок слайда
        self.set_xy(self.margin, 3)
        self.set_font("DejaVu", "B", 14)
        self.set_text_color(255, 255, 255)
        self.cell(0, 8, title, ln=1)
        # Сброс цвета
        self.set_text_color(*self.text)
        self.set_xy(self.margin, 18)

    def body_text(self, text, size=11, bold=False, color=None):
        self.set_font("DejaVu", "B" if bold else "", size)
        if color:
            self.set_text_color(*color)
        else:
            self.set_text_color(*self.text)
        self.multi_cell(self.content_w, 5.5, text)
        self.ln(1.5)

    def bullet(self, text, size=10.5):
        self.set_font("DejaVu", "", size)
        self.set_text_color(*self.text)
        # Отступ для буллета
        x = self.get_x()
        self.cell(4, 5.5, "•", ln=0)
        self.multi_cell(self.content_w - 4, 5.5, text)
        self.ln(1)

    def mini_table(self, headers, rows, col_widths=None, font_size=9):
        if col_widths is None:
            n = len(headers)
            col_widths = [self.content_w / n] * n
        # Заголовки
        self.set_font("DejaVu", "B", font_size)
        self.set_fill_color(230, 236, 240)
        self.set_text_color(*self.accent)
        for i, h in enumerate(headers):
            self.cell(col_widths[i], 6, h, border=1, align='C', fill=True)
        self.ln()
        # Строки
        self.set_font("DejaVu", "", font_size)
        self.set_text_color(*self.text)
        for row in rows:
            # Вычисляем максимальную высоту строки
            max_h = 6
            for i, cell in enumerate(row):
                lines = self.multi_cell(col_widths[i], 5, str(cell), split_only=True)
                h = len(lines) * 5
                if h > max_h:
                    max_h = h
            # Рисуем
            x_start = self.get_x()
            y_start = self.get_y()
            for i, cell in enumerate(row):
                self.set_xy(x_start + sum(col_widths[:i]), y_start)
                self.multi_cell(col_widths[i], 5, str(cell), border=1, align='L')
            self.set_xy(x_start, y_start + max_h)
        self.ln(2)

